import json
from pathlib import Path
import tempfile
import tomllib
import unittest

from bind_engine import bind


GIT_URL = 'https://github.com/kevstermcgee/BlueEngine.git'
REVISION = '1441a433a76aa3c8d0f507dfe370a5c9583882b1'
FLAGS = dict(package='be2', version='0.2', **{'default-features': False},
             features=['presentation', 'physics'], optional=True)


class EngineBinding(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        root = Path(self.temporary.name).resolve()
        self.engine = root / 'catalog engine'
        self.engine.mkdir()
        (self.engine / 'Cargo.toml').write_text('[package]\nname = "be2"\nversion = "0.2.0"\n')
        self.manifest = root / 'Cargo.toml'
        self.lock = root / 'Cargo.lock'

    def write_manifest(self, source):
        fields = dict(FLAGS, **source)
        declaration = ', '.join(f'{key} = {json.dumps(value)}' for key, value in fields.items())
        self.manifest.write_text(
            '[package]\nname = "sample"\nversion = "0.1.0"\n\n'
            '[dependencies]\n# Keep the rest of the game manifest.\n'
            f'vesper3d = {{ {declaration} }}\nserde = "=1.0.219"\n')

    def lock_bytes(self, engine_source=''):
        return (
            '# This file is automatically @generated by Cargo.\nversion = 4\n\n'
            '[[package]]\nname = "be2"\nversion = "0.2.0"\n'
            + engine_source + 'dependencies = [\n "serde",\n]\n\n'
            '[[package]]\nname = "unrelated-git-package"\nversion = "0.1.0"\n'
            f'source = "git+{GIT_URL}?rev={REVISION}#{REVISION}"\n\n'
            '[[package]]\nname = "serde"\nversion = "1.0.219"\n'
            'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
            'checksum = "retain-this-byte-for-byte"\n'
        ).encode()

    def assert_bound(self):
        document = tomllib.loads(self.manifest.read_text())
        dependency = document['dependencies']['vesper3d']
        self.assertEqual({key: value for key, value in dependency.items() if key != 'path'}, FLAGS)
        self.assertEqual(Path(dependency['path']), self.engine)
        self.assertEqual(document['dependencies']['serde'], '=1.0.219')

    def test_path_uses_catalog_engine_without_changing_dependency_flags_or_lock(self):
        self.write_manifest({'path': '../../..'})
        original_lock = self.lock_bytes()
        self.lock.write_bytes(original_lock)

        bind(self.manifest, self.engine)

        self.assert_bound()
        self.assertEqual(self.lock.read_bytes(), original_lock)

    def test_git_revision_tag_and_branch_remove_only_the_engine_lock_source(self):
        for selector, pin in (('rev', REVISION), ('tag', 'v0.2.0'), ('branch', 'main')):
            with self.subTest(selector=selector):
                self.write_manifest({'git': GIT_URL, selector: pin})
                source_line = f'source = "git+{GIT_URL}?{selector}={pin}#{REVISION}"\n'
                self.lock.write_bytes(self.lock_bytes(source_line))

                bind(self.manifest, self.engine)

                self.assert_bound()
                self.assertEqual(self.lock.read_bytes(), self.lock_bytes())

    def test_unsupported_or_ambiguous_dependencies_fail_before_writing_either_file(self):
        declarations = {
            'missing': '[dependencies]\nserde = "1"\n',
            'registry': '[dependencies]\nvesper3d = { package = "be2", version = "0.2" }\n',
            'explicit-registry': '[dependencies]\nvesper3d = { package = "be2", registry = "other", version = "0.2" }\n',
            'workspace': '[dependencies]\nvesper3d = { workspace = true }\n',
            'string': '[dependencies]\nvesper3d = "0.2"\n',
            'wrong-package': '[dependencies]\nvesper3d = { package = "another-engine", path = "old" }\n',
            'two-sources': f'[dependencies]\nvesper3d = {{ package = "be2", path = "old", git = "{GIT_URL}" }}\n',
            'dependency-table': '[dependencies.vesper3d]\npackage = "be2"\npath = "old"\n',
            'two-declarations': '[dependencies]\nvesper3d = { package = "be2", path = "old" }\n'
                                '[target.\'cfg(windows)\'.dependencies]\n'
                                'vesper3d = { package = "be2", path = "another" }\n',
        }
        for kind, declaration in declarations.items():
            with self.subTest(kind=kind):
                original_manifest = declaration.encode()
                original_lock = self.lock_bytes()
                self.manifest.write_bytes(original_manifest)
                self.lock.write_bytes(original_lock)

                with self.assertRaises(ValueError):
                    bind(self.manifest, self.engine)

                self.assertEqual(self.manifest.read_bytes(), original_manifest)
                self.assertEqual(self.lock.read_bytes(), original_lock)

    def test_git_lock_missing_ambiguous_or_unknown_engine_source_fails_before_writing(self):
        source_line = f'source = "git+{GIT_URL}?rev={REVISION}#{REVISION}"\n'
        lock_variants = {
            'missing-engine': self.lock_bytes(source_line).replace(b'name = "be2"', b'name = "other"'),
            'ambiguous-engine': self.lock_bytes(source_line) + b'\n[[package]]\nname = "be2"\nversion = "0.3.0"\n',
            'registry-engine': self.lock_bytes('source = "registry+https://github.com/rust-lang/crates.io-index"\n'),
        }
        for kind, original_lock in lock_variants.items():
            with self.subTest(kind=kind):
                self.write_manifest({'git': GIT_URL, 'rev': REVISION})
                original_manifest = self.manifest.read_bytes()
                self.lock.write_bytes(original_lock)

                with self.assertRaises(ValueError):
                    bind(self.manifest, self.engine)

                self.assertEqual(self.manifest.read_bytes(), original_manifest)
                self.assertEqual(self.lock.read_bytes(), original_lock)


if __name__ == '__main__':
    unittest.main()
